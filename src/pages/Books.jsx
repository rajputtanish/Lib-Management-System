import React, { useEffect, useState } from "react";
import Sidebar from "../components/Sidebar";
import IssueBook from "../components/IssueBook";
import { envData } from "../data";

function Books() {
  const [inventory, setInventory] = useState([]);
  const [search, setSearch] = useState("");
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);
  const [showIssueBookForm, setShowIssueBookForm] = useState(); // New state for issue book form visibility

  // New state to manage which form is currently visible
  const [activeForm, setActiveForm] = useState(null);

  const [newBook, setNewBook] = useState({
    title: "",
    author: "",
    department: "",
    quantity: 1,
  });

  // const [newBorrower, setNewBorrower] = useState({
  //   rollNo: "",
  //   name: "",
  //   email: "",
  //   phone: "",
  //   date: "",
  //   bookId: "",
  // });

  const [returnBookId, setReturnBookId] = useState("");

  const [removeBookId, setRemoveBookId] = useState("");

  useEffect(() => {
    const fetchInventory = async () => {
      try {
        const response = await fetch(`${envData.apiUrl}/books`);
        if (!response.ok) {
          throw new Error("Failed to fetch books from the server.");
        }
        const data = await response.json();
        setInventory(data);
      } catch (err) {
        setError(err.message);
      } finally {
        setIsLoading(false);
      }
    };
    fetchInventory();
  }, []);

  const handleAddBook = async (e) => {
    e.preventDefault();

    if (
      !newBook.title ||
      !newBook.author ||
      !newBook.department ||
      newBook.quantity < 1
    ) {
      alert("Please fill in all fields correctly.");
      return;
    }

    try {
      // 1. Send the new book data to your backend API
      const response = await fetch(`${envData.apiUrl}/books`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(newBook),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Failed to add book");
      }

      // 2. Update local state with the exact copies generated by the backend
      setInventory([...inventory, ...data.addedBooks]);

      // 3. Reset form and close it
      setNewBook({ title: "", author: "", department: "", quantity: 1 });
      setActiveForm(null);
      alert(data.message); // Show success message
    } catch (error) {
      alert(`Error: ${error.message}`);
    }
  };

  const handleReturnBook = async (e) => {
    e.preventDefault();
    if (!returnBookId) {
      alert("Please enter a Book ID.");
      return;
    }

    try {
      const response = await fetch(`${envData.apiUrl}/books-issued/return`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ bookId: returnBookId }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Failed to return book");
      }

      // 2. Update local inventory state only if backend call succeeds
      const updatedInventory = inventory.map((book) =>
        book.id === returnBookId ? { ...book, available: true } : book,
      );

      setInventory(updatedInventory);
      alert(`Book ${returnBookId} successfully returned!`);

      // 3. Clean up the form
      setReturnBookId("");
      setActiveForm(null);
    } catch (error) {
      alert(`Error: ${error.message}`);
    }
  };

  const handleRemoveBook = async (e) => {
    e.preventDefault();
    if (!removeBookId) {
      alert("Please enter at least one Book ID.");
      return;
    }

    // Parse the string into a clean array: "BK-1, BK-2 " -> ["BK-1", "BK-2"]
    const idsArray = removeBookId
      .split(",")
      .map((id) => id.trim())
      .filter((id) => id !== "");

    try {
      const response = await fetch(`${envData.apiUrl}/books`, {
        method: "DELETE",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ bookIds: idsArray }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Failed to remove books");
      }

      // Update local state by filtering out all deleted books
      setInventory(inventory.filter((book) => !idsArray.includes(book.id)));
      
      alert(data.message);
      setRemoveBookId("");
      setActiveForm(null);
    } catch (error) {
      alert(`Error: ${error.message}`);
    }
  };

  // const handleAddMoreCopies = (bookGroup) => {
  //   const quantityInput = window.prompt(
  //     `How many new copies of "${bookGroup.title}" are you adding to the library?`,
  //     "1",
  //   );
  //   const quantityToAdd = parseInt(quantityInput);

  //   if (!quantityToAdd || quantityToAdd < 1) return;

  //   const newCopies = [];
  //   const baseId = `BK-${Math.floor(1000 + Math.random() * 9000)}`;

  //   for (let i = 0; i < quantityToAdd; i++) {
  //     newCopies.push({
  //       id: `${baseId}-NEW${i + 1}`,
  //       title: bookGroup.title,
  //       author: bookGroup.author,
  //       department: bookGroup.department,
  //       available: true,
  //     });
  //   }

  //   setInventory([...inventory, ...newCopies]);
  // };

  const groupedBooks = Object.values(
    inventory.reduce((acc, book) => {
      if (!acc[book.title]) {
        acc[book.title] = {
          title: book.title,
          author: book.author,
          department: book.department,
          copies: [],
        };
      }
      acc[book.title].copies.push({ id: book.id, available: book.available });
      return acc;
    }, {}),
  );

  const filteredBooks = groupedBooks.filter(
    (book) =>
      book.title.toLowerCase().includes(search.toLowerCase()) ||
      book.author.toLowerCase().includes(search.toLowerCase()) ||
      book.department.toLowerCase().includes(search.toLowerCase()),
  );

  const handleBorrow = (bookGroup) => {
    const nextAvailableCopy = bookGroup.copies.find((c) => c.available);

    if (nextAvailableCopy) {
      setInventory(
        inventory.map((item) =>
          item.id === nextAvailableCopy.id
            ? { ...item, available: false }
            : item,
        ),
      );
    }

    setShowIssueBookForm(null);
  };

  // Helper styles for the toggle buttons
  // const buttonStyle = {
  //   padding: "10px 15px",
  //   cursor: "pointer",
  //   background: "#007bff",
  //   color: "#fff",
  //   border: "none",
  //   borderRadius: "4px",
  //   fontWeight: "bold",
  // };

  // const activeButtonStyle = {
  //   ...buttonStyle,
  //   background: "#0056b3",
  //   boxShadow: "inset 0 3px 5px rgba(0,0,0,0.125)",
  // };

  if (showIssueBookForm) {
    return (
      <IssueBook
        onClose={() => setShowIssueBookForm(null)}
        book={showIssueBookForm}
        onIssue={handleBorrow}
      />
    );
  }

  return (
    <div className="flex h-screen bg-slate-50 overflow-hidden font-sans w-full">
      {/* Sidebar is now properly integrated into a flex layout */}
      <Sidebar />

      {/* Main Content Area - Scrollable */}
      <div className="flex-1 overflow-y-auto p-6 md:p-8 pt-6">
        <div className="max-w-6xl mx-auto">
          <h2 className="text-3xl font-bold text-slate-800 tracking-tight mt-0 mb-8">
            Library Inventory Management
          </h2>

          {/* Action Buttons Container */}
          <div className="flex flex-wrap gap-4 mb-8">
            <button
              className={`px-5 py-2.5 rounded-xl font-semibold transition-all duration-200 shadow-sm border focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500 ${
                activeForm === "add"
                  ? "bg-blue-700 text-white border-blue-700 ring-4 ring-blue-100"
                  : "bg-white text-slate-700 border-slate-300 hover:bg-slate-50 hover:border-slate-400"
              }`}
              onClick={() => setActiveForm(activeForm === "add" ? null : "add")}
            >
              {activeForm === "add" ? "Close Add Form" : "Add New Book"}
            </button>

            <button
              className={`px-5 py-2.5 rounded-xl font-semibold transition-all duration-200 shadow-sm border focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500 ${
                activeForm === "return"
                  ? "bg-blue-700 text-white border-blue-700 ring-4 ring-blue-100"
                  : "bg-white text-slate-700 border-slate-300 hover:bg-slate-50 hover:border-slate-400"
              }`}
              onClick={() =>
                setActiveForm(activeForm === "return" ? null : "return")
              }
            >
              {activeForm === "return" ? "Close Return Form" : "Return Book"}
            </button>

            {/* Add this button inside your <div className="flex flex-wrap gap-4 mb-8"> */}
            <button
              className={`px-5 py-2.5 rounded-xl font-semibold transition-all duration-200 shadow-sm border focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-red-500 ${
                activeForm === "remove"
                  ? "bg-red-600 text-white border-red-600 ring-4 ring-red-100"
                  : "bg-white text-slate-700 border-slate-300 hover:bg-slate-50 hover:border-slate-400 hover:text-red-600"
              }`}
              onClick={() => setActiveForm(activeForm === "remove" ? null : "remove")}
            >
              {activeForm === "remove" ? "Close Remove Form" : "Remove Book"}
            </button>

          </div>

          {/* Conditionally Rendered Forms */}
          {activeForm === "add" && (
            <div className="bg-white p-6 md:p-8 rounded-2xl shadow-sm border border-slate-200 mb-8 animate-in fade-in slide-in-from-top-2 duration-300">
              <h3 className="text-xl font-bold text-slate-800 mt-0 mb-5">
                Add New Book
              </h3>
              <form onSubmit={handleAddBook} className="space-y-4">
                <input
                  type="text"
                  placeholder="Book Title"
                  value={newBook.title}
                  onChange={(e) =>
                    setNewBook({ ...newBook, title: e.target.value })
                  }
                  required
                  className="w-full p-3.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
                />
                <input
                  type="text"
                  placeholder="Author"
                  value={newBook.author}
                  onChange={(e) =>
                    setNewBook({ ...newBook, author: e.target.value })
                  }
                  required
                  className="w-full p-3.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
                />
                <input
                  type="text"
                  placeholder="Department (e.g., Computer Science)"
                  value={newBook.department}
                  onChange={(e) =>
                    setNewBook({ ...newBook, department: e.target.value })
                  }
                  required
                  className="w-full p-3.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
                />
                <div className="flex flex-col sm:flex-row gap-4 pt-2">
                  <input
                    type="number"
                    min="1"
                    placeholder="Qty"
                    value={newBook.quantity}
                    onChange={(e) =>
                      setNewBook({
                        ...newBook,
                        quantity: parseInt(e.target.value) || 1,
                      })
                    }
                    required
                    className="w-full sm:w-32 p-3.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
                  />
                  <button
                    type="submit"
                    className="flex-1 bg-green-600 hover:bg-green-700 text-white font-semibold py-3.5 px-6 rounded-xl shadow-sm transition-colors duration-200 outline-none focus:ring-2 focus:ring-green-500 focus:ring-offset-2"
                  >
                    Save to Inventory
                  </button>
                </div>
              </form>
            </div>
          )}

          {activeForm === "return" && (
            <div className="bg-white p-6 md:p-8 rounded-2xl shadow-sm border border-slate-200 mb-8 animate-in fade-in slide-in-from-top-2 duration-300">
              <h3 className="text-xl font-bold text-slate-800 mt-0 mb-5">
                Return Book
              </h3>
              <form onSubmit={handleReturnBook} className="space-y-4">
                <input
                  type="text"
                  placeholder="Book ID"
                  value={returnBookId}
                  onChange={(e) => setReturnBookId(e.target.value)}
                  required
                  className="w-full p-3.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
                />
                <button
                  type="submit"
                  className="w-full sm:w-auto bg-green-600 hover:bg-green-700 text-white font-semibold py-3.5 px-8 rounded-xl shadow-sm transition-colors duration-200 outline-none focus:ring-2 focus:ring-green-500 focus:ring-offset-2"
                >
                  Return Book
                </button>
              </form>
            </div>
          )}

          {activeForm === "remove" && (
            <div className="bg-rose-50 p-6 md:p-8 rounded-2xl shadow-sm border border-rose-200 mb-8 animate-in fade-in slide-in-from-top-2 duration-300">
              <h3 className="text-xl font-bold text-rose-800 mt-0 mb-5 flex items-center gap-2">
                ⚠️ Remove Book from Library
              </h3>
              <form onSubmit={handleRemoveBook} className="space-y-4">
                <input
                type="text"
                placeholder="Enter Book IDs separated by commas (e.g. BK-1234-A, BK-1234-B)"
                value={removeBookId}
                onChange={(e) => setRemoveBookId(e.target.value)}
                required
                className="w-full p-3.5 bg-white border border-rose-300 rounded-xl text-slate-800 focus:bg-white focus:ring-2 focus:ring-red-500 focus:border-red-500 outline-none transition-all"
              />
                <button
                  type="submit"
                  className="w-full sm:w-auto bg-red-600 hover:bg-red-700 text-white font-semibold py-3.5 px-8 rounded-xl shadow-sm transition-colors duration-200 outline-none focus:ring-2 focus:ring-red-500 focus:ring-offset-2"
                >
                  Permanently Delete
                </button>
              </form>
            </div>
          )}

          <hr className="border-t border-slate-200 my-10" />

          <h2 className="text-2xl font-bold text-slate-800 mb-6 flex items-center gap-2 mt-0">
            📚 Library Collection
          </h2>

          <div className="mb-8">
            <input
              type="text"
              placeholder="Search by title, author, or department..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full p-4 pl-5 bg-white border border-slate-300 rounded-2xl shadow-sm text-slate-800 focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none transition-all"
            />
          </div>

          {isLoading && (
            <div className="text-center p-8 text-blue-600 font-medium animate-pulse">
              Loading library inventory...
            </div>
          )}

          {error && (
            <div className="p-4 mb-6 bg-red-50 border border-red-200 text-red-600 rounded-xl text-center font-medium">
              Error: {error}
            </div>
          )}

          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6">
            {filteredBooks.map((book) => {
              const totalCopies = book.copies.length;
              const availableCopies = book.copies.filter((c) => c.available);
              const availableCount = availableCopies.length;

              return (
                <div
                  key={book.title}
                  className="bg-white border border-slate-200 p-6 rounded-2xl shadow-sm hover:shadow-md transition-all duration-200 flex flex-col justify-between group"
                >
                  <div>
                    <h3 className="text-lg font-bold text-slate-900 mb-1 mt-0 group-hover:text-blue-600 transition-colors">
                      {book.title}
                    </h3>
                    <p className="text-slate-500 text-sm mb-4 font-medium">
                      By {book.author}
                    </p>
                    <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-blue-50 text-blue-700 text-xs font-bold tracking-wide">
                      🏢 {book.department}
                    </span>
                  </div>

                  <div className="mt-6 pt-5 border-t border-slate-100">
                    <div className="flex items-center justify-between mb-4 text-sm text-slate-600">
                      <span>Remaining:</span>
                      <span className="font-medium bg-slate-50 px-2 py-1 rounded-md">
                        <strong
                          className={
                            availableCount > 0
                              ? "text-green-600"
                              : "text-red-500"
                          }
                        >
                          {availableCount}
                        </strong>{" "}
                        <span className="text-slate-400">/</span> {totalCopies}{" "}
                        copies
                      </span>
                    </div>

                    <button
                      onClick={() => setShowIssueBookForm(book)}
                      disabled={availableCount === 0}
                      className={`w-full py-3 px-4 rounded-xl font-semibold transition-all duration-200 outline-none focus:ring-2 focus:ring-offset-1 ${
                        availableCount > 0
                          ? "bg-blue-600 hover:bg-blue-700 text-white shadow-sm focus:ring-blue-500"
                          : "bg-slate-100 text-slate-400 cursor-not-allowed"
                      }`}
                    >
                      {availableCount > 0 ? "Borrow Copy" : "Out of Stock"}
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}

export default Books;
